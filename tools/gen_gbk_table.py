#!/usr/bin/env python3
"""Generate src/core/gbk_table.cpp, the GBK code table the line parser decodes with.

Each entry is what Python's own "gbk" codec makes of one byte pair: lead byte 0x81..0xFE,
trail byte 0x40..0xFE without 0x7F, and 0 where Python raises. The table is therefore Python's
mapping by construction, so LineParser::decode(bytes, "gbk") equals
bytes.decode("gbk", "replace") on every build, with or without ICU.

    python3 tools/gen_gbk_table.py          rewrite src/core/gbk_table.cpp
    python3 tools/gen_gbk_table.py --check  fail when the file is out of date
"""
import argparse
import pathlib
import sys

LEADS = range(0x81, 0xFF)
TRAILS = [t for t in range(0x40, 0xFF) if t != 0x7F]
PER_LINE = 10  # 190 trail bytes = 19 lines per lead byte

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "core" / "gbk_table.cpp"


def code_point(lead, trail):
    try:
        text = bytes([lead, trail]).decode("gbk")
    except UnicodeDecodeError:
        return 0
    if len(text) != 1 or ord(text) > 0xFFFF:
        sys.exit(f"gbk {lead:02X}{trail:02X} decodes to {text!r}, not one UTF-16 unit")
    return ord(text)


def generate():
    lines = [
        "// Generated by tools/gen_gbk_table.py from Python's gbk codec; do not edit.",
        '#include "core/gbk_table.h"',
        "",
        "namespace fhmi::gbk {",
        "",
        "const char16_t kTable[kLeadCount * kTrailCount] = {",
    ]
    mapped = 0
    for lead in LEADS:
        row = [code_point(lead, trail) for trail in TRAILS]
        mapped += sum(1 for c in row if c)
        lines.append(f"    // {lead:02X}")
        for at in range(0, len(row), PER_LINE):
            lines.append("    " + " ".join(f"0x{c:04X}," for c in row[at:at + PER_LINE]))
    lines += ["};", "", "} // namespace fhmi::gbk", ""]
    return "\n".join(lines), mapped


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the file is out of date")
    args = parser.parse_args()
    text, mapped = generate()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.exit(f"{OUTPUT} is out of date; run {pathlib.Path(__file__).name}")
        print(f"{OUTPUT} is current ({mapped} pairs)")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}: {len(LEADS) * len(TRAILS)} entries, {mapped} pairs mapped")


if __name__ == "__main__":
    main()
